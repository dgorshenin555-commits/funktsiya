/**
 * Разделы направления. objectType учитывается только у ПД (у остальных направлений
 * в CRM object_type_id = NULL), по умолчанию — капитальные объекты.
 */
export function getDirectionSections(
  direction: DirectionCode,
  objectType: DirectionObjectType = 'capital_building',
): DirectionSection[] {
  switch (direction) {
    case 'pd':
      return objectType === 'linear_object' ? PD_LINEAR_SECTIONS : PD_CAPITAL_SECTIONS;
    case 'rd':
      return RD_SECTIONS;
    case 'calc':
      return CALC_SECTIONS;
    case 'expert':
      return EXPERT_SECTIONS;
    case 'survey':
      return SURVEY_SECTIONS;
    case 'draft':
      return DRAFT_SECTIONS;
    case 'scan3d':
      return SCAN3D_SECTIONS;
  }
}

// Плоский список шифров для поиска и фильтров. Шифры повторяются между направлениями
// (СМ, ПОС, ВК…), поэтому список уникальный; разделы без шифра пропущены.
export const DIRECTION_SECTION_CODES: string[] = Array.from(
  new Set(
    DIRECTIONS.flatMap((d) =>
      (d.byObjectType
        ? [...getDirectionSections(d.code, 'capital_building'), ...getDirectionSections(d.code, 'linear_object')]
        : getDirectionSections(d.code)
      ).flatMap((s) => (s.code ? [s.code] : [])),
    ),
  ),
);

// === Совместимость с прежними категориями исполнителя ===
// До перехода на справочник CRM анкета хранила свои коды (designer, surveyor,
// calculator, draftsman, scan3d, expert). Разворачиваем их в направления, чтобы
// у зарегистрированных раньше исполнителей выбор не обнулился. «Проектировщик»
// раскрывается в два направления: он ведёт и проектную, и рабочую документацию.
const LEGACY_MAP: Record<string, DirectionCode[]> = {
  designer: ['pd', 'rd'],
  surveyor: ['survey'],
  calculator: ['calc'],
  draftsman: ['draft'],
  scan3d: ['scan3d'],
  expert: ['expert'],
};

export function LEGACY_TO_DIRECTIONS(saved?: string[] | null): DirectionCode[] {
  if (!saved || saved.length === 0) return [];
  const known = new Set(DIRECTIONS.map((d) => d.code));
  const out = new Set<DirectionCode>();
  for (const v of saved) {
    if (known.has(v as DirectionCode)) out.add(v as DirectionCode);
    else (LEGACY_MAP[v] || []).forEach((d) => out.add(d));
  }
  return [...out];
}
